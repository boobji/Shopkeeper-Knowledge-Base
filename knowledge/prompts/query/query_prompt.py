# 意图路由提示词模板
# 分类标准：
#   chitchat     闲聊、寒暄、夸奖、与商品咨询无关的话（如"你好"、"你是谁"、"谢谢"）
#   meta         售后政策/物流/退换货/发票/门店等元问题（知识库里没有这类内容）
#   troubleshoot 故障排查、维修、报错处理（步骤与原因类知识在知识图谱里最强）
#   compare      多款商品/型号之间的对比咨询
#   product_qa   其他产品使用、参数、功能类咨询（默认）
INTENT_ROUTE_TEMPLATE = """请判断用户消息的意图，从以下五类中选择一类：
- chitchat：闲聊/寒暄/礼貌用语，与产品咨询无关
- meta：售后政策、物流、退换货、发票等商家服务类问题
- troubleshoot：故障排查、维修、异常报错类问题
- compare：两款或多款商品之间的对比
- product_qa：产品使用方法、参数、功能等常规产品咨询

如果是 chitchat，请顺便用一句自然、友好的话回复用户（30字以内），并引导他咨询产品问题；
其他意图 reply 留空字符串。

请直接返回JSON格式结果，格式如下：
{{
    "intent": "product_qa",
    "reply": ""
}}

用户消息：{query}"""


